let cached = null;

function demoAccountSet() {
  if (cached) return cached;
  const raw = process.env.DEMO_ACCOUNTS || '';
  cached = new Set(
    raw
      .split(',')
      .map((s) => s.trim().toLowerCase())
      .filter(Boolean)
  );
  return cached;
}

// यह खाता डेमो-सूची में है या नहीं
function isDemoAccount(identifier) {
  const id = String(identifier || '').trim().toLowerCase();
  if (!id) return false;
  return demoAccountSet().has(id);
}

module.exports = { isDemoAccount };
