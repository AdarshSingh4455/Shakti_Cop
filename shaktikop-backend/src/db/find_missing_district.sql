-- बिना ज़िले वाले (district = NULL) अधिकारी/एडमिन — पहचान व सुधार
--
-- क्यों ज़रूरी है:
-- ऐप में दायरा (scope) तय करने वाली लगभग हर जांच ज़िले पर टिकी है। थानों के नाम
-- सिर्फ़ (ज़िला + थाना) मिलाकर अद्वितीय होते हैं — "कोतवाली" जैसा नाम अकेले 65
-- ज़िलों में मौजूद है। इसलिए अगर किसी अधिकारी का ज़िला खाली रह जाए, तो वह हर
-- district-आधारित जांच में "छूट" पा जाता है और सिर्फ़ थाने के नाम से मिलान होता
-- है — यानी उसे दूसरे ज़िलों की उसी नाम वाली शिकायतें/अधिकारी दिख सकते हैं।
--
-- नए खाते अब बिना ज़िले के बन ही नहीं सकते (सभी बनाने वाले endpoints पर जांच
-- जोड़ी जा चुकी है)। यह फ़ाइल पहले से बने खातों के लिए है।
--
-- ⚠️ यह फ़ाइल जान-बूझकर कुछ अपने-आप नहीं बदलती — सही ज़िला कौन-सा है, यह सिर्फ़
--    आप जानते हैं। पहले नीचे की जांच चलाकर देखें कि कौन-से खाते प्रभावित हैं,
--    फिर हर एक के लिए सही ज़िला ख़ुद भरें।
--
-- चलाने के लिए:
--   psql "$DATABASE_URL" -f src/db/find_missing_district.sql
-- ============================================================

-- 1️⃣ जिन अधिकारियों का ज़िला खाली है
SELECT 'officer' AS type, id, name, badge_id, station, district, rank, is_active
FROM officers
WHERE district IS NULL OR TRIM(district) = ''
ORDER BY is_active DESC, station, name;

-- 2️⃣ जिन एडमिन खातों का ज़िला खाली है
--    (IG/DIG के लिए ज़िला खाली होना सही है — उनका दायरा range_districts में रहता है,
--     इसलिए वे यहां जान-बूझकर छोड़े गए हैं)
SELECT 'admin' AS type, id, name, email, mobile, admin_role, rank, district, is_active
FROM admins
WHERE (district IS NULL OR TRIM(district) = '')
  AND admin_role <> 'super_admin'
  AND (rank IS NULL OR rank NOT IN ('IG', 'DIG'))
ORDER BY is_active DESC, name;

-- 3️⃣ सुधार कैसे करें — ऊपर की सूची से हर खाते के लिए, सही ज़िला भरकर चलाएं:
--
--   UPDATE officers SET district = 'लखनऊ' WHERE id = '<यहां ऊपर वाली id डालें>';
--   UPDATE admins   SET district = 'लखनऊ' WHERE id = '<यहां ऊपर वाली id डालें>';
--
-- सुधार के बाद 1️⃣ और 2️⃣ दोबारा चलाकर पुष्टि करें कि अब कोई पंक्ति नहीं बची।
