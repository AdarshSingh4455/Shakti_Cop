export const DISTRICTS_WITH_STATIONS = { ...FALLBACK_DISTRICTS_WITH_STATIONS };
export const DISTRICTS = Object.keys(DISTRICTS_WITH_STATIONS);

// 🆕 सर्वर से मिले असली अंग्रेज़ी नाम — अब यह डेटा-आधारित है (LocationDataScreen
// से Super Admin भरता है), पहले जैसी सिर्फ़ "प्रमुख ज़िलों" तक सीमित hardcoded
// dictionary नहीं। tt()/LocaleContext इसे पहले जांचता है, हार्डकोडेड सूची को
// सिर्फ़ तब जब यहां कुछ न मिले (पुराने डेटा के लिए backward-compatible fallback)।
export const DISTRICTS_EN_MAP = {};       // { 'लखनऊ': 'Lucknow', ... }
export const STATIONS_EN_BY_DISTRICT = {}; // { 'लखनऊ': { 'हजरतगंज': 'Hazratganj', ... }, ... }
export const STATIONS_EN_FLAT = {};        // { 'हजरतगंज': 'Hazratganj', ... } — तेज़ lookup के लिए (tt() से)

export function stationsForDistrict(district) {
  return DISTRICTS_WITH_STATIONS[district] || DISTRICTS_WITH_STATIONS[DISTRICTS[0]] || ['कोतवाली'];
}

// सर्वर से मिला असली डेटा यहाँ भरा जाता है (AppContext से एक बार कॉल होता है)
export function setLocationData(stationsByDistrict, districtsEnMap, stationsEnByDistrict) {
  if (!stationsByDistrict || Object.keys(stationsByDistrict).length === 0) return;

  for (const key of Object.keys(DISTRICTS_WITH_STATIONS)) delete DISTRICTS_WITH_STATIONS[key];
  for (const [district, stations] of Object.entries(stationsByDistrict)) {
    DISTRICTS_WITH_STATIONS[district] = stations;
  }

  DISTRICTS.length = 0;
  DISTRICTS.push(...Object.keys(DISTRICTS_WITH_STATIONS).sort());

  for (const key of Object.keys(DISTRICTS_EN_MAP)) delete DISTRICTS_EN_MAP[key];
  Object.assign(DISTRICTS_EN_MAP, districtsEnMap || {});

  for (const key of Object.keys(STATIONS_EN_BY_DISTRICT)) delete STATIONS_EN_BY_DISTRICT[key];
  Object.assign(STATIONS_EN_BY_DISTRICT, stationsEnByDistrict || {});

  for (const key of Object.keys(STATIONS_EN_FLAT)) delete STATIONS_EN_FLAT[key];
  for (const perDistrict of Object.values(STATIONS_EN_BY_DISTRICT)) {
    Object.assign(STATIONS_EN_FLAT, perDistrict);
  }
}
