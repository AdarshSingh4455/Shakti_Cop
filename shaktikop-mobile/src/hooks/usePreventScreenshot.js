import { useEffect } from 'react';
import * as ScreenCapture from 'expo-screen-capture';

// 🔒 सुरक्षा सुधार: यह ऐप बेहद संवेदनशील जानकारी दिखाता है — पीड़िता का नाम, पता,
// मोबाइल, घरेलू-हिंसा/उत्पीड़न का विवरण। अगर फ़ोन साझा हो, चोरी हो, या किसी और के
// हाथ लग जाए, तो कोई भी स्क्रीनशॉट लेकर या स्क्रीन-रिकॉर्ड करके यह डेटा बाहर ले जा
// सकता था। यह hook ऐसे स्क्रीन पर स्क्रीनशॉट/स्क्रीन-रिकॉर्डिंग को रोकता है
// (Android पर पूरी तरह ब्लॉक होता है; iOS पर स्क्रीनशॉट रोका नहीं जा सकता — पर
// स्क्रीन-रिकॉर्डिंग होने पर पता चल सकता है, भविष्य में सूचना जोड़ी जा सकती है)।
//
// इस्तेमाल: किसी भी संवेदनशील स्क्रीन के कॉम्पोनेन्ट के अंदर सिर्फ़ यह लाइन जोड़ें —
//   usePreventScreenshot();
export function usePreventScreenshot() {
  useEffect(() => {
    let active = true;
    (async () => {
      try {
        await ScreenCapture.preventScreenCaptureAsync();
      } catch (e) {
        // कुछ डिवाइस/Expo Go पर उपलब्ध न हो — चुपचाप छोड़ें, बाकी ऐप काम करता रहे
      }
    })();
    return () => {
      active = false;
      // इस स्क्रीन से बाहर जाते ही सामान्य व्यवहार वापस — ताकि नागरिक अपनी ही अन्य
      // ज़रूरी स्क्रीन (जैसे ID/रसीद) का स्क्रीनशॉट सामान्य रूप से ले सकें
      ScreenCapture.allowScreenCaptureAsync().catch(() => {});
    };
  }, []);
}
